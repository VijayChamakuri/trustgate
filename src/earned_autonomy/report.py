"""Render results/REPORT.md from metrics.json and the governed marts."""

from __future__ import annotations

import json
import math

from .evaluate import MONTH_NAMES
from .load import connect
from .paths import RESULTS


def pct(x, d=1):
    return "n/a" if x is None else f"{x * 100:.{d}f}%"


def tau(x):
    return "locked" if x is None or (isinstance(x, float) and math.isnan(x)) else f"{x:.3f}"


def money(x):
    return f"${x:,.0f}"


def findings() -> dict:
    con = connect(read_only=True)
    q = lambda s: con.sql(s).df()  # noqa: E731
    out = {
        "saas": q("""select merchant_name, owner_dept, months_billed, round(total_spend) as total_spend,
                            price_change_pct, is_price_creep, is_orphaned, round(spend_after_owner_left) as after_left,
                            is_duplicate_tool
                     from marts.mart_saas_subscriptions order by total_spend desc"""),
        "queue": q("""select decision, count(*) as n, round(sum(amount)) as dollars
                      from marts.mart_review_queue where posted_date >= date '2026-07-01' group by 1 order by 2 desc"""),
        "top_queue": q("""select posted_date, merchant_name, amount, decision, rationale
                          from marts.mart_review_queue where posted_date >= date '2026-07-01' limit 5"""),
        "spend": q("""select gl_name, round(sum(spend)) as spend from marts.mart_spend_monthly
                      group by 1 order by 2 desc limit 8"""),
    }
    con.close()
    return out


def render() -> str:
    m = json.loads((RESULTS / "metrics.json").read_text())
    f = findings()
    a = m["autonomy"]
    L: list[str] = []
    w = L.append
    w("# Results\n")
    w(
        f"_Generated by `ea all`. {m['data']['transactions']:,} transactions; live evaluation on "
        f"{m['data']['live_transactions']:,} transactions in the final four months. Extractor: `{m['data']['extractor']}`._\n"
    )

    w("## 1. How much autonomy did the policy agent earn?\n")
    w("Live months only. Every row is scored against audited gold labels.\n")
    w("| Policy | Auto-actioned | Wrong auto-actions | Error rate (95% CI) | Policy leakage | Human queue | Total cost |")
    w("|---|---:|---:|---|---:|---:|---:|")
    names = [
        ("human_reviews_everything", "Human reviews everything"),
        ("trust_engine_everywhere", "Trust the rules engine everywhere"),
        ("thresholds_from_reviewer_history", "Thresholds set from reviewer history"),
        ("point_estimate_thresholds", "Thresholds from audited gold, point estimate"),
        ("earned_without_novelty_guard", "+ Wilson upper bound (audited gold)"),
        ("earned_without_value_tiers", "+ novelty guard"),
        ("earned_autonomy", "**+ value tiers = earned autonomy**"),
    ]
    for k, label in names:
        r = a[k]
        ci = r["auto_error_ci"]
        w(
            f"| {label} | {pct(r['automation_rate'])} | {r['auto_errors']} | {pct(r['auto_error_rate'], 2)} "
            f"({pct(ci[0], 2)}–{pct(ci[1], 2)}) | {money(r['leaked_dollars'])} | {r['human_queue']:,} | {money(r['total_cost'])} |"
        )
    w(
        f"\nCost model: {m['costs']['review_minutes']:.0f} reviewer-minutes at ${m['costs']['reviewer_hourly']:.0f}/h per human review, "
        "leaked dollars at face value (half for review-worthy items), "
        f"${m['costs']['wrongful_reject']:.0f} per wrongful auto-reject.\n"
    )
    w("![rollout](rollout_by_month.png)\n")
    w(
        "| Month | Phase | Audited labels | Auto-approve τ (<$500) | Auto-approve τ (≥$500) | Auto-reject τ | Held by novelty guard | Auto-actioned | Error rate |"
    )
    w("|---|---|---:|---:|---:|---:|---:|---:|---:|")
    for r in a["earned_by_month"]:
        w(
            f"| {MONTH_NAMES[r['month_index']]} | {r['phase']} | {r['audited_so_far']:,} | {tau(r['tau_approve'])} | {tau(r['tau_approve_high'])} | {tau(r['tau_reject'])} "
            f"| {r['novel_held']:,} | {pct(r['automation_rate'])} | {pct(r['auto_error_rate'], 2)} |"
        )
    w("\n![tradeoff](tradeoff_curve.png)\n")

    pe = m["policy_engine"]
    v = m["verifier"]
    w("## 2. Policy engine and verifier\n")
    w(f"- Rules engine decision accuracy (live): **{pct(pe['live_accuracy'])}**")
    w(
        f'- Verifier AUC for "is this decision right?": **{v["live_auc"]:.3f}** live (shadow {v["shadow_auc"]:.3f}); Brier {v["live_brier"]:.4f}\n'
    )
    w("| Policy section | Violations (live) | Recall | Citation precision |")
    w("|---|---:|---:|---:|")
    for sec, r in pe["section_recall"].items():
        w(f"| §{sec} | {r['support']} | {pct(r['recall'])} | {pct(r['precision'])} |")
    w("\n![calibration](calibration.png)\n")

    eq = m["extractor_quality"]
    w("## 3. Where perception fails (rules extractor)\n")
    w("| Signal | Precision | Recall | Support |")
    w("|---|---:|---:|---:|")
    for k in ("alcohol_on_meals", "premium_cabin", "personal_memo"):
        w(f"| {k} | {pct(eq[k]['precision'])} | {pct(eq[k]['recall'])} | {eq[k]['support']} |")
    w(
        f"\nMeal type accuracy {pct(eq['meal_type_accuracy'])}; attendee count parsed {pct(eq['attendee_count_parsed'])}; "
        f"nightly rate parsed {pct(eq['nightly_rate_parsed'])}.\n"
    )
    w("**Engine misses (said APPROVE, policy violated), by first violated section:**\n")
    w("| Section | Count | Median verifier confidence | Example |")
    w("|---|---:|---:|---|")
    for b in m["failure_analysis"]["engine_misses"]:
        ex = b["example_memo"] or b["example_receipt"] or b["example_descriptor"]
        w(f"| §{b['section']} | {b['count']} | {b['median_confidence']:.2f} | `{str(ex)[:70]}` |")
    w("\n**Largest wrong auto-actions under earned autonomy:**\n")
    w("| Descriptor | Amount | Memo | Agent | Gold |")
    w("|---|---:|---|---|---|")
    for e in m["failure_analysis"]["wrong_auto_actions"][:8]:
        w(
            f"| `{e['descriptor_raw']}` | ${e['amount']:,.2f} | {e['memo'] or ''} | {e['decision']} ({e['confidence']:.3f}) | {e['gold_decision']} §{e['gold_reasons']} |"
        )

    g = m["gl_coding"]
    w("\n## 4. GL coding\n")
    w(f"- Merchant→GL lookup table: **{pct(g['live_accuracy_merchant_lookup'])}** live accuracy")
    w(
        f"- Calibrated model: **{pct(g['live_accuracy_model'])}** live (shadow {pct(g['shadow_accuracy_model'])}; the gap is memo-phrasing drift)"
    )
    w(
        f"- Earned auto-posting without the novelty guard: {pct(g['unguarded_auto_post_coverage'])} auto-posted at "
        f"**{pct(g['unguarded_auto_post_error_rate'], 2)}** error (budget {pct(m['budgets']['gl'], 0)}, broken by drift)"
    )
    w(
        f"- With the novelty guard: **{pct(g['auto_post_coverage'])}** auto-posted at **{pct(g['auto_post_error_rate'], 2)}** error\n"
    )
    w("| Month | Threshold | Auto-posted | Error on auto-posted | Model accuracy on all |")
    w("|---|---:|---:|---:|---:|")
    for r in g["by_month"]:
        w(
            f"| {MONTH_NAMES[r['month_index']]} | {tau(r['tau'])} | {pct(r['coverage'])} | {pct(r['auto_error_rate'], 2)} | {pct(r['overall_accuracy'])} |"
        )

    mr = m["merchant_resolution"]
    w("\n## 5. Merchant resolution\n")
    w(
        f"- {mr['descriptors']:,} distinct descriptors; MATCH precision **{pct(mr['match_precision'], 2)}**, "
        f"wrong-merge rate {pct(mr['wrong_merge_rate'], 2)}, registry recall {pct(mr['registry_recall'])}"
    )
    w(
        f"- New-vendor recall {pct(mr['new_vendor_recall'])}; escalated to a human {pct(mr['escalation_rate'])}; "
        f"look-alike guardrail blocks {mr['guardrail_blocks']}; protected-pair confusions **{mr['protected_pair_confusions']}**\n"
    )

    w("## 6. What the governed marts surface\n")
    s = f["saas"]
    creep, orphan, dup = s[s.is_price_creep], s[s.is_orphaned], s[s.is_duplicate_tool]
    w(
        f"- **Price creep:** {len(creep)} subscriptions up more than 5% since they started "
        f"(largest: {creep.sort_values('price_change_pct', ascending=False).head(3).apply(lambda r: f'{r.merchant_name} +{r.price_change_pct:.0%}', axis=1).str.cat(sep=', ')})."
    )
    w(
        f"- **Orphaned subscriptions:** {len(orphan)} still billing after the owner left, {money(orphan.after_left.sum())} since departure."
    )
    w(
        f"- **Duplicate tools:** {dup.merchant_name.nunique()} tools paid for by more than one cardholder "
        f"({', '.join(sorted(dup.merchant_name.unique())[:6])}).\n"
    )
    w("Review queue, live months:\n")
    w("| Decision | Items | Dollars |")
    w("|---|---:|---:|")
    for r in f["queue"].itertuples():  # decision = what the agent proposed to the reviewer
        w(f"| {r.decision} | {r.n:,} | {money(r.dollars)} |")
    return "\n".join(L) + "\n"


def write_report() -> None:
    (RESULTS / "REPORT.md").write_text(render())
